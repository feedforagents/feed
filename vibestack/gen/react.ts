// The React face of a generated state machine: gen/<name>.react.ts beside gen/<name>.effect.vibe, in a package that
// depends on react (units.ts).
import { SENDER } from "./classify.ts";

/**
 * `text` is gen/<name>.ts. A state machine gets `useMachine`, the one bridge from its `Machine` service to a
 * component: the state as the service publishes it, and `enabled` and `send` for what the component offers. A
 * library gets nothing.
 */
export function reactHook(name: string, source: string, text: string): string | undefined {
  const step = text.match(new RegExp(`^export function step\\(current: .+?, event: Event(, ${SENDER}: .+?)?\\): `, "m"));
  if (!step) return undefined;
  const by = step[1] ? `, ${SENDER}: By` : "";
  const passed = step[1] ? `, ${SENDER}` : "";
  return [
    `// GENERATED from ${source} by vibestack/spec.ts. Do not edit: change the spec and run \`pnpm gen\`.`,
    `// gen/${name}.effect.vibe for React: the state of its Machine for a component, and the events the rules allow.`,
    `import { Cause, Effect, Exit, type ManagedRuntime, Stream } from "effect";`,
    `import { useRef, useSyncExternalStore } from "react";`,
    `import { type Event, type Rejected, Machine, enabled, step } from "./${name}.effect.vibe";`,
    ``,
    `type State = Parameters<typeof enabled>[0];`,
    ...(step[1] ? [`type By = Parameters<typeof enabled>[2];`] : []),
    `type Sent = ReturnType<typeof step>;`,
    ``,
    `type Snapshot<E> = { readonly state: State | undefined; readonly cause?: Cause.Cause<E> };`,
    `type SelectedSnapshot<E, Selected> = { readonly state: Selected; readonly cause?: Cause.Cause<E> };`,
    `type Selector<Selected> = (state: State | undefined) => Selected;`,
    `type Equality<Selected> = (previous: Selected, next: Selected) => boolean;`,
    `type Memo<E, Selected> = {`,
    `  snapshot: Snapshot<E>;`,
    `  select: Selector<Selected>;`,
    `  equals: Equality<Selected>;`,
    `  result: SelectedSnapshot<E, Selected>;`,
    `};`,
    `type MachineResult<E, Selected> = {`,
    `  readonly state: Selected;`,
    `  readonly cause: Cause.Cause<E> | undefined;`,
    `  readonly can: (event: Event${by}) => boolean;`,
    `  readonly send: (event: Event${by}) => Promise<Exit.Exit<Sent, Rejected | E>>;`,
    `};`,
    `type Store<E> = {`,
    `  readonly get: () => Snapshot<E>;`,
    `  readonly subscribe: (notify: () => void) => () => void;`,
    `  readonly can: (event: Event${by}) => boolean;`,
    `  readonly send: (event: Event${by}) => Promise<Exit.Exit<Sent, Rejected | E>>;`,
    `};`,
    `const stores = new WeakMap<object, unknown>();`,
    ``,
    `function storeFor<E>(runtime: ManagedRuntime.ManagedRuntime<Machine, E>): Store<E> {`,
    `  const known = stores.get(runtime) as Store<E> | undefined;`,
    `  if (known) return known;`,
    `  let seen: Snapshot<E> = { state: undefined };`,
    `  const listeners = new Set<() => void>();`,
    `  let active: object | undefined;`,
    `  let stop: (() => void) | undefined;`,
    `  const store: Store<E> = {`,
    `    get: () => seen,`,
    `    subscribe: (notify) => {`,
    `      listeners.add(notify);`,
    `      if (!active) {`,
    `        const token = {};`,
    `        active = token;`,
    `        const show = (next: Snapshot<E>) => {`,
    `          if (active !== token) return;`,
    `          if (Object.is(seen.state, next.state) && Object.is(seen.cause, next.cause)) return;`,
    `          seen = next;`,
    `          for (const listener of listeners) listener();`,
    `        };`,
    `        const fiber = runtime.runFork(Machine.use((machine) => Stream.runForEach(machine.changes, (state) => Effect.sync(() => show({ state })))));`,
    `        stop = () => fiber.interruptUnsafe();`,
    `        fiber.addObserver((exit) => { if (Exit.isFailure(exit) && !Cause.hasInterruptsOnly(exit.cause)) show({ ...seen, cause: exit.cause }); });`,
    `      }`,
    `      return () => {`,
    `        listeners.delete(notify);`,
    `        if (!listeners.size) { active = undefined; stop?.(); stop = undefined; }`,
    `      };`,
    `    },`,
    `    can: (event: Event${by}) => seen.state !== undefined && enabled(seen.state, event${passed}),`,
    `    send: (event: Event${by}) => runtime.runPromiseExit(Machine.use((machine) => machine.send(event${passed}))),`,
    `  };`,
    `  stores.set(runtime, store);`,
    `  return store;`,
    `}`,
    ``,
    `/**`,
    ` * The Machine that \`runtime\` provides, shared by its components. \`state\` is undefined until the machine has`,
    ` * given one, and \`cause\` is why it gives none or no more. Pass \`select\` (and optional \`equals\`) to re-render`,
    ` * only when the selected slice changes. \`can\` and \`send\` are cached per runtime.`,
    ` */`,
    `export function useMachine<E>(runtime: ManagedRuntime.ManagedRuntime<Machine, E>): MachineResult<E, State | undefined>;`,
    `export function useMachine<E, Selected>(`,
    `  runtime: ManagedRuntime.ManagedRuntime<Machine, E>,`,
    `  select: Selector<Selected>,`,
    `  equals?: Equality<Selected>,`,
    `): MachineResult<E, Selected>;`,
    `export function useMachine<E, Selected = State | undefined>(`,
    `  runtime: ManagedRuntime.ManagedRuntime<Machine, E>,`,
    `  select?: Selector<Selected>,`,
    `  equals: Equality<Selected> = Object.is,`,
    `): MachineResult<E, Selected> {`,
    `  const store = storeFor(runtime);`,
    `  const memo = useRef<Memo<E, Selected> | undefined>(undefined);`,
    `  const getSnapshot: () => SelectedSnapshot<E, Selected> = select === undefined`,
    `    ? (store.get as () => SelectedSnapshot<E, Selected>)`,
    `    : () => {`,
    `        const nextSnapshot = store.get();`,
    `        const current = memo.current;`,
    `        if (current !== undefined && Object.is(current.snapshot, nextSnapshot) && Object.is(current.select, select) && Object.is(current.equals, equals)) {`,
    `          return current.result;`,
    `        }`,
    `        const nextState = select(nextSnapshot.state);`,
    `        if (current !== undefined && Object.is(current.result.cause, nextSnapshot.cause) && equals(current.result.state, nextState)) {`,
    `          current.snapshot = nextSnapshot;`,
    `          current.select = select;`,
    `          current.equals = equals;`,
    `          return current.result;`,
    `        }`,
    `        const result: SelectedSnapshot<E, Selected> = { state: nextState, cause: nextSnapshot.cause };`,
    `        memo.current = { snapshot: nextSnapshot, select, equals, result };`,
    `        return result;`,
    `      };`,
    `  const { state, cause } = useSyncExternalStore(store.subscribe, getSnapshot, getSnapshot);`,
    `  return { state, cause, can: store.can, send: store.send };`,
    `}`,
    ``,
    `export function useMachineSelector<E, Selected>(`,
    `  runtime: ManagedRuntime.ManagedRuntime<Machine, E>,`,
    `  select: Selector<Selected>,`,
    `  equals: Equality<Selected> = Object.is,`,
    `): Selected {`,
    `  return useMachine(runtime, select, equals).state;`,
    `}`,
    ``,
  ].join("\n");
}
